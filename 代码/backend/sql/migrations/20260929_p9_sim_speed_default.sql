-- P9：仿真默认倍速 60 → 10（2026-09-29）
-- 背景：60 倍是按"跑回归"选的——两分钟的航程两秒飞完。人手动调度一单，
--       点完起飞再切到监控大屏，飞机已经落地摘除了，看起来就是"大屏上没有送货信息"。
--       10 倍下 2 分钟航程约 12 秒，起飞→巡航→进近→送达在屏上都看得清。
-- 幂等：只改仍是出厂值 60 的行。用户自己在「系统管理 → 仿真控制」调过（比如回归时
--       临时调到 60/120）的，这里不覆盖。重复执行第二次起 0 行受影响。
-- ---------------------------------------------------------------------

UPDATE sys_config
   SET config_value = '10',
       remark = '仿真倍速：1 为实时，10 表示 1 秒推进 10 秒飞行时间（大屏看得清全程）'
 WHERE config_key = 'sim_speed_factor' AND config_value = '60';
