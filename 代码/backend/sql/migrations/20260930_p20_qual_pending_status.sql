-- 2026-09-30 资质上传/新建（B 批次）：给 status 增加入口态「0 待审核」
-- =====================================================================
-- 要解决的问题：qualification.status 的默认值是 1（有效），而这张表过去**没有任何写入方**
-- （只有 POST /qualifications/<id>/audit 在改状态）。也就是说"上传资质"这个口子一旦开出来，
-- 插入即有效 = 复审这道闸门被绕过。修法不是给新建加权限点，而是把 0 定成唯一的入口态：
-- 所有新建一律落 0 待审核，连 resource:qualification 的审核岗自己登记也不例外——
-- 只要存在一条"谁建谁有效"的路径，台账里的有效证就还是能没有依据。
--
-- 为什么默认值也要改：视图里会显式写 status=0，但漏写一条 INSERT 就会掉回 1。
-- 默认值改 0 之后，"忘了给状态"的结果是待审核（保守），而不是有效（放行）。
-- 这类"列定义"必须三处同步，少一处就会出现演示库与测试库口径不一致：
--   1) 本迁移（演示库只能增量改）
--   2) sql/tianshu-ddl-v1.sql:178（测试库整库重建走它，见 tests/conftest.bootstrap_database）
--   3) app/models/qualification.py 的 ORM default（代码里 new 对象时用的就是它）
--
-- 影响面：只改列默认值与注释，不回写任何既有行。演示库现有 3 行人员资质
-- （id 1/2/3，status 分别 1 有效、2 即将到期、3 已过期）取值保持原样，file_url 全为 NULL。
-- 状态集合的读侧口径见 app/blueprints/resource.py 的 QUAL_STATUS。
--
-- 幂等：MODIFY COLUMN 重复执行结果一致，无需条件判断。

ALTER TABLE qualification MODIFY COLUMN status TINYINT NOT NULL DEFAULT 0 COMMENT '0待审核1有效2即将到期3已过期4驳回';
